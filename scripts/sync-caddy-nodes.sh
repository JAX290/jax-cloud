#!/bin/bash
# =============================================================================
#  节点面板反代自动生成（JAX CLOUD）
#
#  根据数据库里的节点，为每台节点生成一个 Caddy 站点片段：
#      http://100.124.251.8:<31000+节点id>  ->  http://<节点IP>:<面板端口>
#  端口都落在 docker-compose.yml 里一次性映射好的 31001-31050 区间内。
#
#  免登录的 Cookie 不在这里写（由 refresh-panel-sessions.sh 负责），
#  这里只 import /etc/caddy/snippets/node-<id>.caddy 那一段。
#
#  用法：
#    sync-caddy-nodes.sh --once           # 立刻同步一次（默认）
#    sync-caddy-nodes.sh --check          # 只检查，不写文件
#    sync-caddy-nodes.sh --install-cron   # 安装定时任务：
#                                          每分钟同步反代 + 每 3 小时刷新面板免登录
#
#  环境变量（一般不用改）：
#    APP_DIR=/opt/jax-app  PANEL_PROXY_HOST=100.124.251.8  CADDY_CONTAINER=jax-caddy
# =============================================================================
set -u

APP_DIR="${APP_DIR:-/opt/jax-app}"
DB_FILE="${DB_FILE:-$APP_DIR/data/jax.db}"
NODES_DIR="${NODES_DIR:-$APP_DIR/caddy-nodes}"
SNIPPETS_DIR="${SNIPPETS_DIR:-$APP_DIR/caddy-snippets}"
# 主控 Tailscale 地址：优先环境变量，其次读 .env 的 PANEL_HOST，最后用默认值
if [ -z "${PANEL_PROXY_HOST:-}" ] && [ -f "$APP_DIR/.env" ]; then
  PANEL_PROXY_HOST="$(grep -E '^PANEL_HOST=' "$APP_DIR/.env" 2>/dev/null | head -1 | cut -d= -f2-)"
fi
PROXY_HOST="${PANEL_PROXY_HOST:-100.124.251.8}"
PORT_BASE="${PANEL_PROXY_PORT_BASE:-31000}"
PORT_MAX="${PANEL_PROXY_PORT_MAX:-31050}"
CADDY_CONTAINER="${CADDY_CONTAINER:-jax-caddy}"
CADDY_CONFIG="${CADDY_CONFIG:-/etc/caddy/Caddyfile}"
LOCK_FILE="${LOCK_FILE:-/tmp/jax-caddy-sync.lock}"

MODE="${1:---once}"
say() { printf '%s %s\n' "$(date '+%F %T')" "$*"; }

# 防并发（cron 一分钟一次，正常几毫秒就结束）
if command -v flock >/dev/null 2>&1; then
  exec 9>"$LOCK_FILE"
  flock -n 9 || { say "another sync is running, skip"; exit 0; }
fi

case "$MODE" in
  --install-cron)
    [ -f "$APP_DIR/scripts/sync-caddy-nodes.sh" ] || { say "script not found under $APP_DIR/scripts"; exit 1; }
    chmod +x "$APP_DIR/scripts/sync-caddy-nodes.sh" "$APP_DIR/scripts/refresh-panel-sessions.sh" 2>/dev/null || true
    tmp=$(mktemp)
    # 保留其它定时任务（如健康检查），只替换本项目的两条
    crontab -l 2>/dev/null | grep -v 'sync-caddy-nodes\.sh' | grep -v 'refresh-panel-sessions\.sh' > "$tmp"
    cat >> "$tmp" <<EOF
* * * * * $APP_DIR/scripts/sync-caddy-nodes.sh --once >> /var/log/jax-caddy-sync.log 2>&1
0 */3 * * * $APP_DIR/scripts/refresh-panel-sessions.sh >> /var/log/jax-panel-sessions.log 2>&1
EOF
    crontab "$tmp"
    rm -f "$tmp"
    say "cron installed:"
    crontab -l | grep -E 'sync-caddy-nodes|refresh-panel-sessions'
    exit 0
    ;;
  --check) WRITE="0" ;;
  --once|"") WRITE="1" ;;
  *) echo "unknown option: $MODE"; exit 2 ;;
esac

if [ ! -f "$DB_FILE" ]; then
  say "db not found: $DB_FILE"
  exit 1
fi
mkdir -p "$NODES_DIR" "$SNIPPETS_DIR"

# import 的 glob 至少要匹配到一个文件，否则 caddy 起不来；放一个只含注释的占位文件
if [ ! -f "$NODES_DIR/_placeholder.caddy" ]; then
  printf '# keep this file: makes "import /etc/caddy/nodes/*.caddy" always match\n' > "$NODES_DIR/_placeholder.caddy"
fi

# 读节点：id<TAB>name<TAB>ip<TAB>panel_port
NODE_LINES=$(python3 - "$DB_FILE" <<'PY'
import sqlite3, sys
try:
    con = sqlite3.connect(sys.argv[1])
    for row in con.execute("select id, name, ip, panel_port from nodes order by id"):
        nid, name, ip, port = row
        if not nid or not ip:
            continue
        name = (name or "").replace("\t", " ").strip()
        port = int(port or 2053)
        print("%s\t%s\t%s\t%s" % (nid, name, str(ip).strip(), port))
    con.close()
except Exception as e:
    sys.stderr.write("db error: %s\n" % e)
    sys.exit(1)
PY
) || { say "read db failed"; exit 1; }

changed=0
seen=""
tmpf=$(mktemp)
while IFS=$'\t' read -r nid name ip port; do
  [ -z "${nid:-}" ] && continue
  proxy_port=$((PORT_BASE + nid))
  if [ "$proxy_port" -gt "$PORT_MAX" ]; then
    say "WARN node $nid: port $proxy_port > $PORT_MAX (增加 docker-compose 端口区间)"
    continue
  fi
  seen="$seen$nid
"
  target="$NODES_DIR/node-${nid}.caddy"
  cat > "$tmpf" <<EOF
# AUTO-GENERATED by scripts/sync-caddy-nodes.sh -- do not edit by hand
# node ${nid} ${name}
http://${PROXY_HOST}:${proxy_port} {
	encode gzip
	reverse_proxy ${ip}:${port} {
		header_up X-Forwarded-Proto http
		import /etc/caddy/snippets/node-${nid}.caddy
	}
}
EOF
  if [ "$WRITE" = "1" ]; then
    if ! cmp -s "$tmpf" "$target"; then
      cp "$tmpf" "$target"
      chmod 0644 "$target"
      changed=1
      say "updated node-${nid}.caddy -> :${proxy_port} => ${ip}:${port}"
    fi
    # Cookie 片段必须存在，否则 caddy 的 import 会报错
    if [ ! -f "$SNIPPETS_DIR/node-${nid}.caddy" ]; then
      : > "$SNIPPETS_DIR/node-${nid}.caddy"
      chmod 0644 "$SNIPPETS_DIR/node-${nid}.caddy"
    fi
  else
    cmp -s "$tmpf" "$target" || say "would update node-${nid}.caddy"
  fi
done <<< "$NODE_LINES"
rm -f "$tmpf"

# 清掉已删除节点的片段
if [ "$WRITE" = "1" ]; then
  for f in "$NODES_DIR"/node-*.caddy; do
    [ -e "$f" ] || continue
    base=$(basename "$f" .caddy)
    nid="${base#node-}"
    if ! printf '%s' "$seen" | grep -qx "$nid"; then
      rm -f "$f"
      rm -f "$SNIPPETS_DIR/node-${nid}.caddy"
      changed=1
      say "removed stale node-${nid}.caddy"
    fi
  done
fi

if [ "$WRITE" != "1" ]; then
  say "check done"
  exit 0
fi

if [ "$changed" = "1" ]; then
  if docker ps --format '{{.Names}}' 2>/dev/null | grep -qx "$CADDY_CONTAINER"; then
    if out=$(docker exec "$CADDY_CONTAINER" caddy reload --config "$CADDY_CONFIG" 2>&1); then
      say "caddy reloaded"
    else
      say "caddy reload FAILED: $out"
      exit 1
    fi
  else
    say "caddy container ($CADDY_CONTAINER) not running, config will load next start"
  fi
else
  say "no change"
fi
